CREATE TABLE patients (
    patient_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(40) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    date_of_birth VARCHAR(20) NOT NULL,
    gender VARCHAR(30),
    province VARCHAR(50),
    city VARCHAR(100),
    postal_code VARCHAR(15),
    phone_number VARCHAR(25),
    health_card_number VARCHAR(50) UNIQUE,
    primary_diagnosis VARCHAR(255),
    blood_type VARCHAR(10),
    last_visit_date VARCHAR(20)
);

CREATE TABLE appointments (
    appointment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INTEGER NOT NULL,
    appointment_datetime VARCHAR(30) NOT NULL,
    pharmacist_name VARCHAR(100) NOT NULL,
    appointment_type VARCHAR(100) NOT NULL,
    FOREIGN KEY (patient_id) REFERENCES patients(patient_id)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

